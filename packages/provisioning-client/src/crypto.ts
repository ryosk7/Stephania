// HMAC and sealing constructions from contracts/ble-protocol.md. Pure JS
// (@noble/hashes, @noble/ciphers) so it runs in React Native without native
// crypto modules.
import {chacha20poly1305} from '@noble/ciphers/chacha';
import {hmac} from '@noble/hashes/hmac';
import {sha256} from '@noble/hashes/sha256';

const enc = new TextEncoder();

export const toHex = (b: Uint8Array) => Array.from(b, x => x.toString(16).padStart(2, '0')).join('');
export function fromHex(s: string): Uint8Array {
  if (s.length % 2 !== 0 || !/^[0-9a-fA-F]*$/.test(s)) throw new Error('invalid hex');
  const out = new Uint8Array(s.length / 2);
  for (let i = 0; i < out.length; i++) out[i] = parseInt(s.slice(i * 2, i * 2 + 2), 16);
  return out;
}

/** u32-BE length prefixed concatenation, identical to the device. */
export function encodeParts(parts: Uint8Array[]): Uint8Array {
  const total = parts.reduce((n, p) => n + 4 + p.length, 0);
  const out = new Uint8Array(total);
  const view = new DataView(out.buffer);
  let o = 0;
  for (const p of parts) { view.setUint32(o, p.length); out.set(p, o + 4); o += 4 + p.length; }
  return out;
}

const mac = (key: Uint8Array, parts: (Uint8Array | string)[]) =>
  hmac(sha256, key, encodeParts(parts.map(p => (typeof p === 'string' ? enc.encode(p) : p))));

export const claimProof = (secret: Uint8Array, nonce: Uint8Array, ownerId: string) => mac(secret, ['t3box-claim-v1', nonce, ownerId]);
export const deriveOwnerKey = (secret: Uint8Array, nonce: Uint8Array, ownerId: string) => mac(secret, ['t3box-owner-key-v1', nonce, ownerId]);
export const operationProof = (ownerKey: Uint8Array, nonce: Uint8Array, operation: string, payload: Uint8Array) =>
  mac(ownerKey, ['t3box-operation-v1', nonce, operation, payload]);

export const OWNER_ID = /^[A-Za-z0-9._-]{1,64}$/;

/**
 * Parse the setup QR (`t3box-setup:v1:<32 hex>:<8 hex SHA-256 check>`),
 * generated by tools/setup-page. Returns the 16-byte setup secret.
 */
export function parseSetupUri(text: string): Uint8Array | null {
  const m = /^t3box-setup:v1:([0-9a-f]{32}):([0-9a-f]{8})$/.exec(text.trim().toLowerCase());
  if (!m) return null;
  const secret = fromHex(m[1]);
  if (secret.every(b => b === 0)) return null;
  return toHex(sha256(secret).subarray(0, 4)) === m[2] ? secret : null;
}

/**
 * Application-layer confidentiality (protocol v2): ChaCha20-Poly1305 with
 * key = MAC(owner_key, "t3box-seal-v1"), nonce = first 12 bytes of the
 * single-use operation nonce, AAD = operation name.
 */
export function seal(ownerKey: Uint8Array, opNonce: Uint8Array, operation: string, plaintext: Uint8Array): Uint8Array {
  return chacha20poly1305(mac(ownerKey, ['t3box-seal-v1']), opNonce.subarray(0, 12), new TextEncoder().encode(operation)).encrypt(plaintext);
}
